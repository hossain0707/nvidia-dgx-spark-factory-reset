"""GRUB configuration uses only commands available in the tested netboot loader."""
from __future__ import annotations

import re

from .config import RecoveryError, Session


def kernel_args(session: Session, *, install: bool = False, disk: str = "") -> str:
    args = ["boot=casper", "ip=dhcp",
            f"iso-url=http://{session.server}:{session.http_port}/recovery.iso",
            "fsck.mode=skip", "nouveau.modeset=0", "no-nvsm-enable", "no-reorder-uefi",
            "force-platform=dgx_spark", "console=ttyS0,921600", "console=tty0",
            "cloud-init=disabled", "sbsa_gwdt.action=1", "nopersistent",
            "initcall_blacklist=tegra234_cbb_init"]
    if install:
        if not re.fullmatch(r"/dev/nvme[0-9]+n[0-9]+", disk):
            raise RecoveryError("Only a whole NVMe namespace is an allowed install target")
        args += ["autoinstall", f"force-bootdisk={disk}", "module_blacklist=r8169"]
    else:
        args += ["noswap", "module_blacklist=r8169,nvme,nvme_core",
                 "modprobe.blacklist=r8169,nvme,nvme_core", "break=casper-bottom", "init=/bin/sh"]
    return " ".join(args)


def render(session: Session, disk: str = "", *, agent: bool = False) -> str:
    config = """# Generated by spark-recovery. STOP is always the default; no timed erase.
set default=0
set timeout=-1
menuentry 'STOP - no installation' {
    echo 'No action performed. Select a diagnostic or explicitly approved installation.'
    sleep --interruptible 5
}
menuentry 'VERIFY ONLY - SSD hidden; stop before installer' {
    echo 'Loading recovery into RAM. NVMe disabled; no autoinstall.'
    linux /casper/vmlinuz """ + kernel_args(session) + """
    initrd /casper/initrd
}
"""
    if agent:
        config = config.replace("initrd /casper/initrd", "initrd /casper/initrd-diagnostic", 1)
        config = config.replace("init=/bin/sh", "init=/bin/sh mkd.diagnostic=1", 1)
        if not disk:
            config = config.replace("set default=0\nset timeout=-1", "set default=1\nset timeout=5", 1)
    if disk:
        args = kernel_args(session, install=True, disk=disk)
        config += f"""
submenu 'ERASE SSD - ASUS DGX OS installation' {{
    set default=0
    set timeout=-1
    menuentry 'CANCEL - preserve existing data' {{
        echo 'Canceled. Press Esc to return.'
        sleep --interruptible 5
    }}
    menuentry 'CONFIRM ERASE {disk} - START INSTALLATION' {{
        echo 'Erasing the explicitly approved SSD and reinstalling ASUS DGX OS.'
        linux /casper/vmlinuz {args}
        initrd /casper/initrd
    }}
}}
"""
    return config
